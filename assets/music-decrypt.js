  function mimeOf(ext) { return MIME[ext] || 'audio/mpeg'; }

  function sniffAudioExt(data, fallback) {
    fallback = fallback || 'mp3';
    if (hasPrefix(data, [0x49, 0x44, 0x33])) return 'mp3';          // ID3
    if (hasPrefix(data, [0x66, 0x4C, 0x61, 0x43])) return 'flac';    // fLaC
    if (hasPrefix(data, [0x4F, 0x67, 0x67, 0x53])) return 'ogg';     // OggS
    if (data.length >= 8 && hasPrefix(data.subarray(4), [0x66, 0x74, 0x79, 0x70])) return 'm4a';
    if (hasPrefix(data, [0x52, 0x49, 0x46, 0x46])) return 'wav';     // RIFF
    if (hasPrefix(data, [0x30, 0x26, 0xB2, 0x75, 0x8E, 0x66, 0xCF, 0x11, 0xA6, 0xD9, 0x00, 0xAA, 0x00, 0x62, 0xCE, 0x6C])) return 'wma';
    if (hasPrefix(data, [0xFF, 0xF1])) return 'aac';
    if (hasPrefix(data, [0x46, 0x52, 0x4D, 0x38])) return 'dff';     // FRM8
    return fallback;
  }

  /* ---------- NCM 解密 ---------- */
  function buildKeyBox(keyData) {
    var box = new Uint8Array(256);
    for (var i = 0; i < 256; i++) box[i] = i;
    var len = keyData.length;
    var j = 0;
    for (var i = 0; i < 256; i++) {
      j = (box[i] + j + keyData[i % len]) & 0xFF;
      var t = box[i]; box[i] = box[j]; box[j] = t;
    }
    var out = new Uint8Array(256);
    for (var i = 0; i < 256; i++) {
      var ii = (i + 1) & 0xFF;
      var si = box[ii];
      var sj = box[(ii + si) & 0xFF];
      out[i] = box[(si + sj) & 0xFF];
    }
    return out;
  }

  function decryptNcm(arrayBuffer) {
    var raw = new Uint8Array(arrayBuffer);
    if (!hasPrefix(raw, NCM_MAGIC)) return Promise.reject(new Error('不是有效的网易云 ncm 文件'));
    var view = new DataView(arrayBuffer);
    var offset = 10;

    // key 区
    var keyLen = view.getUint32(offset, true); offset += 4;
    if (offset + keyLen > raw.length) return Promise.reject(new Error('ncm 文件已损坏'));
    var keyCipher = new Uint8Array(keyLen);
    for (var i = 0; i < keyLen; i++) keyCipher[i] = raw[offset + i] ^ 0x64;
    offset += keyLen;

    return aesEcbDecrypt(CORE_KEY, keyCipher).then(function (keyPlain) {
      if (keyPlain.length <= 17) throw new Error('ncm 密钥解析失败');
      var keyBox = buildKeyBox(keyPlain.subarray(17));

      // meta 区
      var metaLen = view.getUint32(offset, true); offset += 4;
      var format = '', title = '', artist = '';
      if (metaLen > 0 && offset + metaLen <= raw.length) {
        var metaCipher = new Uint8Array(metaLen);
        for (var m = 0; m < metaLen; m++) metaCipher[m] = raw[offset + m] ^ 0x63;
        offset += metaLen;
        var metaEnc = base64ToBytes(bytesToUtf8(metaCipher.subarray(22)));
        return aesEcbDecrypt(META_KEY, metaEnc).then(function (metaPlain) {
          try {
            var text = bytesToUtf8(metaPlain);
            var colon = text.indexOf(':');
            if (colon >= 0) {
              var obj = JSON.parse(text.slice(colon + 1));
              var main = obj && obj.mainMusic ? obj.mainMusic : obj;
              if (main) {
                format = String(main.format || '').toLowerCase();
                title = String(main.musicName || '');
                if (Array.isArray(main.artist)) artist = main.artist.map(function (a) { return a && a[0]; }).filter(Boolean).join(', ');
              }
            }
          } catch (e) { /* meta 解析失败不阻断播放 */ }
          return finishAudio();
        });
      }
      return finishAudio();

      function finishAudio() {
        offset += view.getUint32(offset + 5, true) + 13;
        if (offset > raw.length) throw new Error('ncm 文件已损坏');
        var audio = raw.subarray(offset);
        for (var c = 0; c < audio.length; c++) audio[c] ^= keyBox[c & 0xFF];
        if (!format) format = sniffAudioExt(audio, 'mp3');
        return {
          ok: true, data: audio, format: format, mime: mimeOf(format),
          title: title, artist: artist
        };
      }
    });
  }

  /* ---------- KGM / VPR 解密 ---------- */
  function getMask(pos) {
    var offset = pos >> 4;
    var value = 0;
    while (offset >= 0x11) {
      value ^= TABLE1[offset % 272];
      offset >>= 4;
      value ^= TABLE2[offset % 272];
      offset >>= 4;
    }
    return MASK_V2[pos % 272] ^ value;
  }

  function decryptKgm(arrayBuffer, isVpr) {
    var raw = new Uint8Array(arrayBuffer);
    var magic = isVpr ? VPR_HEADER : KGM_HEADER;
    if (!hasPrefix(raw, magic)) throw new Error(isVpr ? '不是有效的酷狗 vpr 文件' : '不是有效的酷狗 kgm 文件');
    var view = new DataView(arrayBuffer);
    var headerLen = view.getUint32(0x10, true);
    if (headerLen < 0x2C || headerLen > raw.length) throw new Error('kgm 文件已损坏');
    var key = new Uint8Array(17);
    key.set(raw.subarray(0x1C, 0x2C));
    var data = raw.slice(headerLen);
    for (var i = 0; i < data.length; i++) {
      var med8 = key[i % 17] ^ data[i];
      med8 ^= (med8 & 0xF) << 4;
      var msk8 = getMask(i);
      msk8 ^= (msk8 & 0xF) << 4;
      var d = med8 ^ msk8;
      if (isVpr) d ^= VPR_MASK_DIFF[i % 17];
      data[i] = d;
    }
    var format = sniffAudioExt(data, 'mp3');
    return { ok: true, data: data, format: format, mime: mimeOf(format) };
  }

