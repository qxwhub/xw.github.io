  function hasPrefix(data, prefix) {
    if (prefix.length > data.length) return false;
    for (var i = 0; i < prefix.length; i++) {
      if (data[i] !== prefix[i]) return false;
    }
    return true;
  }

  function bytesToUtf8(b) {
    if (typeof TextDecoder !== 'undefined') {
      try {
        return new TextDecoder('utf-8').decode(b);
      } catch (e) { /* 极老环境回退逐字节 */ }
    }
    var s = '';
    for (var i = 0; i < b.length; i++) s += String.fromCharCode(b[i]);
    return s;
  }

  function bytesToHex(b) {
    var s = '';
    for (var i = 0; i < b.length; i++) {
      s += (b[i] < 16 ? '0' : '') + b[i].toString(16);
    }
    return s;
  }

  // 与 CryptoJS Base64.parse 行为对齐：跳过非法字符
  function base64ToBytes(str) {
    str = str.replace(/[^A-Za-z0-9+\/=]/g, '');
    var bin = global.atob(str);
    var out = new Uint8Array(bin.length);
    for (var i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
    return out;
  }

  // 模拟 AES-128-ECB 解密。
  // 原理：CBC 解密 P_i = AES_D(C_i) ^ C_(i-1)，ECB 解密 P'_i = AES_D(C_i)，
  //       所以 P'_i = P_i ^ C_(i-1)（C_(-1) = IV = 0）。
  // WebCrypto 的 AES-CBC decrypt 强制校验末块 PKCS7，因此先用 encrypt 构造一个
  // "解密后恰为 0x10x16" 的附加尾块（C_append = AES_ENC(0x10x16) ^ C_last），
  // 再对整个密文一次 CBC(IV=0) 解密；输出 = 完整 PKCS7 明文（含 padding 块），
  // 最后按 PKCS7 规则按末字节值裁剪即得真实明文。
  var aesKeyCache = {};
  function aesEcbDecrypt(keyBytes, data) {
    var c = global.crypto;
    if (!c || !c.subtle) return Promise.reject(new Error('当前环境不支持 WebCrypto，无法解密'));
    var L = data.length;
    if (L === 0) return Promise.resolve(new Uint8Array(0));
    if (L % 16 !== 0) return Promise.reject(new Error('密文长度异常'));
    var keyId = bytesToHex(keyBytes);
    var key = aesKeyCache[keyId];
    if (!key) {
      key = c.subtle.importKey('raw', keyBytes, { name: 'AES-CBC' }, false, ['encrypt', 'decrypt']);
      aesKeyCache[keyId] = key;
    }
    return key.then(function (k) {
      var pad = new Uint8Array(16).fill(0x10);
      var tail = data.subarray(L - 16); // 最后一块密文作为 IV
      return c.subtle.encrypt({ name: 'AES-CBC', iv: tail }, k, pad).then(function (append) {
        var padded = new Uint8Array(L + 16);
        padded.set(data);
        padded.set(new Uint8Array(append).subarray(0, 16), L);
        return c.subtle.decrypt({ name: 'AES-CBC', iv: new Uint8Array(16) }, k, padded).then(function (dec) {
          var cbc = new Uint8Array(dec); // 长度 = L（附加块已被 unpad 移除）
          var out = new Uint8Array(L);
          for (var i = 0; i < L; i++) {
            out[i] = cbc[i] ^ (i >= 16 ? data[i - 16] : 0);
          }
          // PKCS7 unpad：末字节即 padding 长度
          var n = out[L - 1];
          if (n > 0 && n <= 16) return out.subarray(0, L - n);
          return out;
        });
      });
    });
  }

